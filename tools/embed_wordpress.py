"""Builds the WordPress embed of the app from index.html.

    python3 -m tools.embed_wordpress v020b > /tmp/181.php      (from the repo root)

On josieandhenry.co.uk the app is not a static folder. The page /grammatizator/ holds a
single shortcode, [php_snippet id="181"], and that snippet (ASE Pro's Code Snippets
Manager; the code lives at wp-content/code-snippets/181.php and in post 181) prints the
app's markup. The css/, js/ and assets/ folders sit under wp-content/uploads/grammatizer/.

Uploaded files are cached for a week by Cloudflare and by browsers, so a release never
overwrites them: each release goes in its own folder (uploads/grammatizer/<version>/)
and the snippet is pointed at it. That also makes rolling back a matter of putting the
previous snippet back.

This script writes that snippet: index.html's stylesheets, body and scripts, with every
relative URL wrapped so WordPress prints it as an absolute one, plus the three things
that only exist on the live site (they are not in index.html):

  - where the backend is (window.GRAMMATIZER_API_BASE)
  - where the artwork is (window.GRAMMATIZER_ASSET_BASE, read by js/machine.js)
  - a <style> hiding the blog's own header and footer on this one page, and its
    floating language flags while the console is showing (they cover the lever)
"""

import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
API_BASE = "https://api.josieandhenry.co.uk"

HEADER = """<?php
/**
 * The Great Automatic Grammatizator -- embedded console app.
 *
 * GENERATED by tools/embed_wordpress.py in the grammatizer repo from index.html.
 * Do not edit here: change the repo and regenerate, or the next release undoes it.
 *
 * This is an ASE Code Snippet (Language: PHP, insert method: Shortcode), and its
 * shortcode is the ENTIRE content of the page it appears on. The app lays itself out
 * and does not expect a theme wrapper.
 *
 * Assets for this release live at wp-content/uploads/grammatizer/%(version)s/ --
 * uploaded directly, not part of this snippet. Each release gets its own folder
 * because uploaded files are cached for a week; never overwrite one in place.
 *
 * The <style> block hides the theme's own header/footer around this page
 * specifically -- targeted by DOM position (the header's builder class, and
 * the section sibling that follows our own main#bde-main), confirmed against
 * this site's actual rendered markup, so it can't ever catch our own content.
 */

$grammatizer_base = trailingslashit( wp_upload_dir()['baseurl'] ) . 'grammatizer/%(version)s/';
?>
<script>
  window.GRAMMATIZER_API_BASE = "%(api_base)s";
  window.GRAMMATIZER_ASSET_BASE = "<?php echo esc_url( $grammatizer_base ); ?>";
</script>
<style>
  header.bde-header-builder,
  main#bde-main ~ section.bde-section { display: none !important; }
  body.breakdance { margin: 0 !important; }
  /* The blog's floating language flags would sit on top of the lever: keep them off
     the console. They stay on the title page. */
  body:has(#screen-console:not([hidden])) .gtranslate_wrapper,
  body:has(#screen-console:not([hidden])) .gt_switcher_wrapper { display: none !important; }
</style>
"""

LOCAL_URL = re.compile(r'\b(href|src)="((?:css|js|assets)/[^"]+)"')


def wrap(match):
    return '%s="<?php echo esc_url( $grammatizer_base . \'%s\' ); ?>"' % (match.group(1), match.group(2))


def build(version):
    with open(os.path.join(ROOT, "index.html")) as fh:
        html = fh.read()
    links = re.findall(r'<link rel="stylesheet" href="css/[^"]+">', html)
    body = html[html.index("<body>") + len("<body>"):html.index("</body>")].strip()
    if "<?" in body:
        raise SystemExit("index.html contains '<?', which PHP would try to run")
    out = HEADER % {"version": version, "api_base": API_BASE}
    out += "\n".join(LOCAL_URL.sub(wrap, link) for link in links) + "\n"
    out += LOCAL_URL.sub(wrap, body) + "\n"
    out += "<?php return '';"
    return out


if __name__ == "__main__":
    if len(sys.argv) != 2 or not re.match(r"^v[0-9]+[a-z]?$", sys.argv[1]):
        raise SystemExit("usage: python3 -m tools.embed_wordpress v020b   (a release folder name)")
    sys.stdout.write(build(sys.argv[1]))
